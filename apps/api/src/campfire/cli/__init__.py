"""本地运维入口：资料与案例的摄取（不暴露成服务端点）。

职责：`python -m campfire.cli ingest <路径>` 摄取到资料库，跑在同一镜像、连同一个库。
边界：不做仓库根 `scripts/` 下的独立脚本；不提供任何服务端点与产品内界面用于资料
录入、审核或知识库管理（`RQ-KB-03`）。
参考：docs/技术设计/technical-details/RAG策略.md 第 7 节、docs/项目结构设计.md 第 2、7 节。
"""

# 设计依据（见 docs/技术设计/technical-details/RAG策略.md 第 7 节与
# docs/项目结构设计.md 第 2、7 节）：

# 入口形态：应用包内的一个 CLI 入口，`python -m campfire.cli ingest <路径>`，
# 跑在同一镜像里、连同一个库。刻意不做成仓库根 `scripts/` 下的独立脚本——
# 它必须复用同一份依赖与同一套写入逻辑（条目表、幂等、嵌入适配），独立脚本必然漂移。
# 「本地」指的是运行环境与触发方式，不是「独立代码」。
# 不提供任何服务端点与产品内界面用于资料录入、审核或知识库管理（`RQ-KB-03`）。
# 条目与检索节点在同一事务内落库。

# 依赖白名单（项目结构设计第 7 节）：`cli` 入口允许依赖 `core/*` 与
# `modules/{library,accounts,memory,profile}`；禁止 import `surfaces/*`、禁止暴露成
# 服务端点、禁止绕过条目表直接写节点。摄取流水线、分块链与嵌入适配的实现归
# `modules/library`（见 docs/技术设计/technical-details/RAG策略.md 第 7 节），
# 本入口只负责命令行形态与调用顺序。

# 为什么放行 `accounts`、`memory` 与 `profile`（2026-09-30 定调级修正 + 随模块落地）：
# `accounts` 是邀请码与账号状态机的归属（运营子命令直接调用）；`memory` 与 `profile`
# 放行是因为账号注销的编排在 `core/auth`，而 `core/*` 不得依赖 `modules/*`——
# 因此「清除该账号的某个领域的数据」的实现放各模块的 `purge.py`，
# 由本入口注入给编排，与其他领域的清除者同一种做法。
# 三处声明（本节、`docs/项目结构设计.md` 第 7 节的 `cli` 行、机械检查
# `apps/api/tests/test_layer_boundaries.py`）必须保持同一份清单。

# 四条与「本地跑」绑定的纪律（RAG 策略第 7 节）：
# 1. 凭据与环境：与运行同一套环境变量入口（`core/config`）。
# 2. 可复现性：必须在同一镜像与同一 lockfile 里跑，否则本地与线上的依赖差异
#    会让分块与嵌入结果不一致。
# 3. 摄取记账：没有应用内审计，由脚本自己写导入记录——批次、文件、条目数、
#    操作者、时间、脚本版本；否则将来撤下某条资料时无法回溯它来自哪份文件、哪一版。
# 4. 换嵌入模型必须整库重建：维度固定 2560，混入不同维度的向量会让检索静默失准。

# 已实现（2026-09-29）：

# `python -m campfire.cli convert <input.html> [--out <output.md>]` —— HTML → Markdown，
# 纯转换：不连库、不调模型、零成本。与 `ingest` 分成两条命令是设计要求
# （RAG 策略第 1.1 节「加工后＋人工核对」才进系统），产物可先审再喂。
# `python -m campfire.cli ingest <路径>` —— 摄取到资料库；元数据可由文件 frontmatter
# 提供，缺 `source` 或 `applicable_scope` 即拒绝入库（不变量）。

# 失败时退出码非 0 并说明原因，不假装成功（缺凭据、路径不存在、写入失败都各自报明
# 原因）。真实嵌入调用已实测可用（`TECH-20` 已关闭，维度 2560）。
