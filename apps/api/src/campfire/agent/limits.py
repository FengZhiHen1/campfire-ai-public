from __future__ import annotations

AGENT_RUN_TIMEOUT_SECONDS = 300.0
"""一条通用响应上限（秒）。超过即按基座第 9 节以明确原因结束，并保留已产生的引用。

依据 docs/技术设计/technical-details/通用基座.md 第 2 节「上限」：**只设一条上限**，
不设步数与 token 上限——步数上限是防死循环的手段，而调用次数与单轮成本由工具契约与
压缩阈值约束；token 上限由压缩阈值与模型窗口兜底。

**2026-10-28 由 180 秒改为 300 秒（实测推翻原值，理由如下，不是"感觉太紧"）**：

一次真实运行不是一次模型调用：一轮「思考 → 调工具 → 读结果 → 再思考 → 成文」的链路
实测至少两次、常见三到四次调用。而模型端点一侧的单次调用延迟在晚高峰可从 6 秒跳到
100 秒以上（原证物：本机 2026-10-28 23:38–23:45 的 `httpx2` 日志里，相邻两次成功调用
相隔 141 秒——也就是说**一次**调用吃掉了 45 秒超时 ×2 次重试 + 余量）。
按 45 秒 × 3 次尝试 = 138 秒的最坏预算算，两次这样的调用就已经 276 秒，
180 秒的上限下这种轮次**必然**被杀，使用者等满三分钟却什么也拿不到。

300 秒的取法有判据：它必须容得下至少两次「最坏预算」的模型调用（2 × 138 = 276 ≤ 300，
见 `apps/api/tests/test_agent_model.py` 的 `test_run_cap_covers_more_than_one_model_call`），
同时仍是可等待的量级。⚠ **改这个数字要同时改 `RUN_MUTEX_TTL_SECONDS`**（会话互斥键
TTL 必须比它大一点，否则运行还没结束锁就放了），代码里已改为从本常量派生。

把这条纪律放在一个模块里，是为了让「为什么没有别的上限」有唯一落点：任何想加第二个
上限的人先读到这里，再决定是改设计还是改代码。

三处由此推出的实现约束：

1. 运行编排调用 SDK 时必须传 `max_turns=None`——SDK 默认 10 轮就是一条步数上限，
   留着它就等于绕过第 2 节的裁决；
2. 模型请求的「超时 × 重试次数 + 退避」必须落在**上限的一半**之内——只保证"一次调用
   装得下"是不够的：一轮运行至少两次调用，一次调用吃满预算就等于这一轮必然超时。
   否则重试会被运行上限从中间砍断，失败原因会从「模型不可用」变成「运行超时」
   （见 `agent.model` 的预算校验，以及上面 2026-10-28 的实测）；
3. 一次运行内不设 token 上限；上下文压力由窗口与压缩处理（压缩策略）。
"""
